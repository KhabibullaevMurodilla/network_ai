"""Builds the static demo snapshot used by the GitHub Pages site.

GitHub Pages can only serve static files, so it cannot run this backend. This
script runs the REAL pipeline in-process (synthetic traffic -> POST
/ingest/batch -> real detector scoring -> real storage in the in-memory test
database), then calls the real /demo/* endpoints and saves their JSON
responses to frontend/public/demo-data/. The Pages site shows that snapshot.

Honest limits: the data is synthetic (generated by ml/generate_telemetry.py),
the snapshot is frozen at build time, and the learning period is disabled here
because every demo source is pre-seeded as an already-baselined segment
(otherwise the first flows of each simulated attacker would go unjudged).

Usage (from backend/):  python scripts/export_demo_snapshot.py
"""
import json
import os
import sys
from pathlib import Path
from unittest.mock import patch

os.environ["ENTITY_LEARNING_MIN_FLOWS"] = "0"
os.environ.setdefault("ALLOWED_ORIGINS", "http://localhost:3000")
os.environ.setdefault("SUPABASE_JWT_SECRET", "snapshot-not-a-real-secret")

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND))
sys.path.insert(0, str(BACKEND / "scripts"))

from fastapi.testclient import TestClient  # noqa: E402

from app.core.config import settings  # noqa: E402
from app.main import app  # noqa: E402
from seed_demo_tenant import seed_demo_tenant  # noqa: E402
from tests.fake_db import FakeDB  # noqa: E402

TENANT = "dd000000-0000-0000-0000-000000000001"
OUT = BACKEND.parent / "frontend" / "public" / "demo-data"


def main() -> None:
    fake = FakeDB()
    targets = [
        "seed_demo_tenant.get_db", "app.core.auth.get_db", "app.routers.ingest.get_db",
        "app.routers.demo.get_db", "app.core.webhooks.get_db", "app.core.response_actions.get_db",
        "app.core.audit.get_db", "app.core.devices.get_db",
    ]
    patches = []
    for t in targets:
        try:
            p = patch(t, return_value=fake)
            p.start()
            patches.append(p)
        except (AttributeError, ModuleNotFoundError):
            pass  # module doesn't import get_db directly; nothing to patch
    settings.DEMO_TENANT_ID = TENANT
    try:
        client = TestClient(app)
        result = seed_demo_tenant(TENANT, client=client)
        print(f"seeded: {result['ingested']} flows, {result['flagged']} flagged")
        OUT.mkdir(parents=True, exist_ok=True)
        for name, path in [("summary", "/demo/summary"), ("anomalies", "/demo/anomalies/recent"),
                           ("entities", "/demo/entities"), ("trend", "/demo/trend?days=14")]:
            r = client.get(path)
            r.raise_for_status()
            (OUT / f"{name}.json").write_text(json.dumps(r.json(), indent=1))
            print(f"wrote {name}.json")
    finally:
        for p in patches:
            p.stop()


if __name__ == "__main__":
    main()
